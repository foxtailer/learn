; Работа с указателями
;
; *p++ = 't'               // 104
;
; p = 0x220                // 110
; for(n=0; n<224; n++)
;     *p++ = 't'
;
; Формируем набор байтов     // 120
; таблицы ASCII
;
; ls = []
; k = 0x20
; for(n=0; n<14; n++)
;     proc 130
;
; proc сформировать строку  // 130
;     таблицы (16 слов + конец)
;     for(n=0; n<16; n++)
;         ls.append(char(k++))
;         ls.append(' ')
;     ls.append('\r')
;     ls.append('\n')

org 100h

Begin:

    nop
    nop

    ; ------------------------------------------------
    ; Заполняем память ES:0220 символом Т.
    ; ------------------------------------------------

    mov al, 54h
    mov di, 0220h
    cld                 ; DF = 0, поэтому DI увеличивается
    stosb               ; ES:[DI] = AL, затем DI = DI + 1

    nop
    nop

    ; ------------------------------------------------
    ; Заполняем 224 байта памяти значением 54h.
    ;
    ; 0E0h = 224
    ;
    ; Записываем:
    ; 0220h ... 02FFh
    ; ------------------------------------------------

    mov di, 0220h
    mov al, 54h
    mov cx, 00E0h       ; 224 повторения
    cld
    rep stosb           ; выполнить STOSB CX раз

    nop
    nop

    ; ------------------------------------------------
    ; Формируем строки ASCII-таблицы.
    ;
    ; AX = 2020h
    ;
    ; AL = 20h — первый ASCII-символ (пробел)
    ; AH = 20h — пробел, который будет второй частью
    ;
    ; DX = 0Eh = 14 строк
    ; ------------------------------------------------

    mov ax, 2020h
    mov di, 0220h
    mov dx, 0Eh         ; 14 строк

next_line:

    call line            ; сформировать одну строку

    dec dx               ; уменьшить количество строк
    jnz next_line        ; если DX != 0, сформировать следующую

    nop
    nop

    int 20h              ; завершить программу


; ====================================================
; line
;
; Формирует одну строку:
;
; 20 21 22 23 ... 2F
;
; между символами ставится пробел.
;
; В конце:
;
; CR LF
;
; То есть строка содержит:
;
; [символ][пробел][символ][пробел]...
; ====================================================

line:

    ; CX = количество ASCII-символов в строке
    mov cx, 0010h        ; 16 символов

line_loop:

    stosw                ; записать AX в ES:[DI]
                         ;
                         ; AL = ASCII-символ
                         ; AH = пробел
                         ;
                         ; после STOSW:
                         ; DI = DI + 2

    inc al               ; перейти к следующему ASCII-символу

    dec cx               ; один символ обработан
    jnz line_loop        ; пока CX != 0 — продолжать

    ; ------------------------------------------------
    ; После 16 символов нужно перейти на новую строку.
    ;
    ; Сохраняем AX, потому что сейчас в AX находится
    ; следующий ASCII-код.
    ; ------------------------------------------------

    push ax

    mov ax, 0A0Dh        ; AL = CR (0Dh)
                         ; AH = LF (0Ah)

    stosw                ; записать CR/LF

    pop ax               ; восстановить следующий ASCII-код

    ret
